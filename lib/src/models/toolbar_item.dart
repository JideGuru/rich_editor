/// The buttons of the built-in toolbar, in their default order.
///
/// Pass a subset, in any order, to [RichEditorOptions.toolbarItems] to
/// choose which buttons show.
enum ToolbarItem {
  bold,
  italic,
  link,
  image,
  video,
  underline,
  strikeThrough,
  superscript,
  subscript,
  clearFormat,
  undo,
  redo,
  blockquote,
  textFormat,
  fontFace,
  fontSize,
  textColor,
  backgroundColor,
  indent,
  outdent,
  alignLeft,
  alignCenter,
  alignRight,
  justify,
  bulletList,
  numberedList,
  checkbox,
}
